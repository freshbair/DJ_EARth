"""Train a small supervised k-NN colour regressor; no weather labels are inferred.
Run from any directory: python ml/train_no2.py
Requires numpy and Pillow. Evaluation is legend reconstruction, NOT field accuracy.
"""
from pathlib import Path
import hashlib
import json
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]

def legend(path):
    pixels = np.asarray(Image.open(path).convert('RGB'))
    assert pixels.shape == (675, 1200, 3), 'Unexpected source dimensions'
    # Exclude arrowheads, outline and tick marks. Labels: 0 at x797, 10 at1113.
    xs = np.arange(800, 1111)
    colors = np.median(pixels[581:586, xs, :], axis=0)
    return colors, (xs - 797) * 10 / (1113 - 797)

def predict(colors, samples, labels):
    distances = np.sum((colors[:, None, :] - samples[None, :, :]) ** 2, axis=2)
    neighbors = np.argsort(distances, axis=1, kind='stable')[:, :5]
    return labels[neighbors].mean(axis=1)

def train():
    source = ROOT / 'assets/no2/march-2015-2019.jpg'
    holdout = ROOT / 'assets/no2/march-2020.jpg'
    colors, labels = legend(source)
    # Fixed stride, fixed k; neither chosen using the later image.
    samples, targets = colors[::2], labels[::2]
    test_colors, test_labels = legend(holdout)
    predictions = predict(test_colors, samples, targets)
    errors = np.abs(predictions - test_labels)
    report = {
        'task': 'Legend colour reconstruction; not weather forecasting',
        'algorithm': '5-nearest-neighbor regression, uniform weights, RGB Euclidean distance',
        'training_samples': len(samples), 'held_out_legend_samples': len(test_labels),
        'mae': float(errors.mean()), 'max_absolute_error': float(errors.max()),
        'constant_mean_baseline_mae': float(np.abs(test_labels - targets.mean()).mean()),
        'units': '10^15 molecules/cm^2 (NO2 column)',
        'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'holdout_sha256': hashlib.sha256(holdout.read_bytes()).hexdigest(),
        'limitations': 'Correlated legend pixels are not independent weather observations. No labelled map pixels or ground measurements were evaluated. Terrain, text, clouds, black pixels and alternate palettes can invalidate readings.'
    }
    model = {'k': 5, 'maxDistance': 32, 'samples': [list(map(float, c)) + [float(t)] for c, t in zip(samples, targets)], 'report': report}
    (ROOT / 'assets/no2/model.js').write_text('/* Generated by ml/train_no2.py */\nglobalThis.DJEarthNO2Model = ' + json.dumps(model, separators=(',', ':')) + ';\n', encoding='utf-8')
    (ROOT / 'ml/no2-evaluation.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report, indent=2))
    assert report['mae'] < 0.4, 'Legend reconstruction failed'
    assert report['mae'] < report['constant_mean_baseline_mae'], 'No improvement over baseline'

if __name__ == '__main__':
    train()
